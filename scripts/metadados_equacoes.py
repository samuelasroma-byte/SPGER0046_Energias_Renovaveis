def enrich(rows):
    assert set(SYMBOL_KEYS)==set(APPLICATIONS)=={r['id'] for r in rows}
    for row in rows:
        row['symbol_details']=[dict(key=key,**deepcopy(SYMBOLS[key])) for key in SYMBOL_KEYS[row['id']].split()]
        row['symbols']='; '.join(f'{s["symbol"]}: {s["description"]} [{s["unit"]}]' for s in row['symbol_details'])+'.'
        role,binding=APPLICATIONS[row['id']]
        row['application_class']=role
        row['application']=USES[role]
        row['code_correspondence']=binding
    return rows
